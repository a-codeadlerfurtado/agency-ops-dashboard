create table if not exists imobi_board.renata_fiel_whatsapp_config (
  id uuid primary key default gen_random_uuid(),
  agency_client_id uuid not null references agency_ops.clients(id) on delete cascade,
  tenant_id uuid null references imobi_board.tenants(id) on delete set null,
  instance_id text not null,
  webhook_secret text not null default encode(gen_random_bytes(24), 'hex'),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (agency_client_id),
  unique (instance_id)
);

create table if not exists imobi_board.renata_fiel_whatsapp_messages (
  id bigint generated by default as identity primary key,
  config_id uuid not null references imobi_board.renata_fiel_whatsapp_config(id) on delete cascade,
  tenant_id uuid null references imobi_board.tenants(id) on delete set null,
  contact_id uuid null references imobi_board.contacts(id) on delete set null,
  opportunity_id uuid null references imobi_board.opportunities(id) on delete set null,
  source_message_row_id bigint null,
  message_id text not null,
  instance_id text not null,
  connected_phone text null,
  lead_phone_normalized text null,
  chat_id text null,
  chat_name text null,
  sender_phone text null,
  sender_name text null,
  from_me boolean not null default false,
  message_type text null,
  body text null,
  status text null,
  event_at timestamptz null,
  received_at timestamptz not null default now(),
  match_status text not null default 'PENDING'
    check (match_status in ('PENDING','MATCHED','NO_TENANT','NO_CONTACT','NO_OPPORTUNITY')),
  raw_json jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (instance_id, message_id)
);

