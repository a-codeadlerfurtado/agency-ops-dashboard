create or replace function imobi_board_priv.trg_link_renata_fiel_tenant()
returns trigger language plpgsql security definer
set search_path = pg_catalog, agency_ops, imobi_board, imobi_board_priv
as $$
declare
  v_cfg imobi_board.renata_fiel_whatsapp_config%rowtype;
  r record;
begin
  if new.agency_client_id is not null then
    update imobi_board.renata_fiel_whatsapp_config
    set tenant_id=new.id,updated_at=now()
    where agency_client_id=new.agency_client_id and tenant_id is distinct from new.id
    returning * into v_cfg;
    if v_cfg.id is not null then
      for r in select id from agency_ops.whatsapp_messages
        where instance_id=v_cfg.instance_id
          and coalesce(is_group,false)=false and coalesce(is_newsletter,false)=false
      loop
        perform imobi_board_priv.sync_renata_fiel_whatsapp_message(r.id);
      end loop;
    end if;
  end if;
  return new;
end;
$$;

