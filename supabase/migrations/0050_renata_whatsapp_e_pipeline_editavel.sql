create or replace function imobi_board.criar_etapa_pipeline(
  p_tenant_id uuid,p_name text,p_kind imobi_board.stage_kind default 'CONTACTED'
) returns uuid language plpgsql security invoker
set search_path=pg_catalog,imobi_board as $$
declare v_pipeline uuid; v_id uuid; v_sort smallint;
begin
  if length(btrim(coalesce(p_name,'')))<1 then
    raise exception 'Digite um nome para a etapa.' using errcode='P0001';
  end if;
  select id into v_pipeline from imobi_board.pipelines
  where tenant_id=p_tenant_id and is_default=true order by created_at limit 1;
  if v_pipeline is null then raise exception 'Pipeline principal nao encontrado.' using errcode='P0001'; end if;
  select coalesce(max(sort_order),-1)+1 into v_sort from imobi_board.pipeline_stages where pipeline_id=v_pipeline;
  insert into imobi_board.pipeline_stages(tenant_id,pipeline_id,name,kind,sort_order)
  values(p_tenant_id,v_pipeline,btrim(p_name),p_kind,v_sort) returning id into v_id;
  return v_id;
end;
$$;

create or replace function imobi_board.atualizar_etapa_pipeline(
  p_stage_id uuid,p_name text,p_kind imobi_board.stage_kind
) returns void language plpgsql security invoker
set search_path=pg_catalog,imobi_board as $$
begin
  if length(btrim(coalesce(p_name,'')))<1 then
    raise exception 'Digite um nome para a etapa.' using errcode='P0001';
  end if;
  update imobi_board.pipeline_stages set name=btrim(p_name),kind=p_kind where id=p_stage_id;
  if not found then raise exception 'Etapa nao encontrada ou sem permissao.' using errcode='P0001'; end if;
end;
$$;

create or replace function imobi_board.mover_etapa_pipeline(p_stage_id uuid,p_direction integer)
returns void language plpgsql security invoker
set search_path=pg_catalog,imobi_board as $$
declare v_pipeline uuid; v_sort smallint; v_other_id uuid; v_other_sort smallint;
begin
  if p_direction not in (-1,1) then raise exception 'Direcao invalida.' using errcode='P0001'; end if;
  select pipeline_id,sort_order into v_pipeline,v_sort from imobi_board.pipeline_stages where id=p_stage_id;
  if v_pipeline is null then raise exception 'Etapa nao encontrada ou sem permissao.' using errcode='P0001'; end if;
  if p_direction=-1 then
    select id,sort_order into v_other_id,v_other_sort from imobi_board.pipeline_stages
    where pipeline_id=v_pipeline and sort_order<v_sort order by sort_order desc limit 1;
  else
    select id,sort_order into v_other_id,v_other_sort from imobi_board.pipeline_stages
    where pipeline_id=v_pipeline and sort_order>v_sort order by sort_order asc limit 1;
  end if;
  if v_other_id is null then return; end if;
  set constraints pipeline_stages_position_uq deferred;
  update imobi_board.pipeline_stages set sort_order=case
    when id=p_stage_id then v_other_sort when id=v_other_id then v_sort else sort_order end
  where id in (p_stage_id,v_other_id);
end;
$$;

create or replace function imobi_board.excluir_etapa_pipeline(p_stage_id uuid)
returns void language plpgsql security invoker
set search_path=pg_catalog,imobi_board as $$
declare v_pipeline uuid; v_total integer; v_used integer;
begin
  select pipeline_id into v_pipeline from imobi_board.pipeline_stages where id=p_stage_id;
  if v_pipeline is null then raise exception 'Etapa nao encontrada ou sem permissao.' using errcode='P0001'; end if;
  select count(*) into v_used from imobi_board.opportunities where stage_id=p_stage_id;
  if v_used>0 then
    raise exception 'Essa etapa ainda tem % lead(s). Mova os leads antes de excluir.',v_used using errcode='P0001';
  end if;
  select count(*) into v_total from imobi_board.pipeline_stages where pipeline_id=v_pipeline;
  if v_total<=1 then raise exception 'O pipeline precisa ter pelo menos uma etapa.' using errcode='P0001'; end if;
  delete from imobi_board.pipeline_stages where id=p_stage_id;
end;
$$;

