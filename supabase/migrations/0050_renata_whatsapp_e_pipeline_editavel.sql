create or replace function imobi_board_priv.normalize_whatsapp_phone(p_value text)
returns text language plpgsql immutable as $$
declare v text;
begin
  v := regexp_replace(coalesce(p_value,''), '[^0-9]', '', 'g');
  if v = '' then return null; end if;
  while length(v) > 11 and left(v,1) = '0' loop v := substr(v,2); end loop;
  if length(v) in (10,11) then return '55' || v; end if;
  return v;
end;
$$;

create or replace function imobi_board_priv.sync_renata_fiel_whatsapp_message(p_source_id bigint)
returns void language plpgsql security definer
set search_path = pg_catalog, agency_ops, imobi_board, imobi_board_priv
as $$
declare
  m agency_ops.whatsapp_messages%rowtype;
  cfg imobi_board.renata_fiel_whatsapp_config%rowtype;
  v_tenant uuid; v_contact uuid; v_opportunity uuid;
  v_phone text; v_match text;
begin
  select * into m from agency_ops.whatsapp_messages where id=p_source_id;
  if not found or coalesce(m.is_group,false) or coalesce(m.is_newsletter,false) then return; end if;

  select * into cfg from imobi_board.renata_fiel_whatsapp_config
  where active=true and instance_id=m.instance_id limit 1;
  if not found then return; end if;

  v_tenant := cfg.tenant_id;
  if v_tenant is null then
    select t.id into v_tenant from imobi_board.tenants t
    where t.agency_client_id=cfg.agency_client_id order by t.created_at desc limit 1;
    if v_tenant is not null then
      update imobi_board.renata_fiel_whatsapp_config
      set tenant_id=v_tenant,updated_at=now() where id=cfg.id;
    end if;
  end if;

  v_phone := imobi_board_priv.normalize_whatsapp_phone(
    case when coalesce(m.from_me,false)
      then coalesce(m.chat_id,m.participant_phone,m.sender_phone)
      else coalesce(m.sender_phone,m.participant_phone,m.chat_id) end
  );

  if v_tenant is null then
    v_match := 'NO_TENANT';
  else
    select c.id into v_contact from imobi_board.contacts c
    where c.tenant_id=v_tenant
      and (c.phone_normalized=v_phone or imobi_board_priv.normalize_whatsapp_phone(c.phone)=v_phone)
    order by c.updated_at desc limit 1;

    if v_contact is null then
      v_match := 'NO_CONTACT';
    else
      select o.id into v_opportunity from imobi_board.opportunities o
      where o.tenant_id=v_tenant and o.contact_id=v_contact
      order by (o.status='OPEN') desc,o.updated_at desc limit 1;
      v_match := case when v_opportunity is null then 'NO_OPPORTUNITY' else 'MATCHED' end;
    end if;
  end if;

  insert into imobi_board.renata_fiel_whatsapp_messages (
    config_id,tenant_id,contact_id,opportunity_id,source_message_row_id,
    message_id,instance_id,connected_phone,lead_phone_normalized,chat_id,chat_name,
    sender_phone,sender_name,from_me,message_type,body,status,event_at,received_at,
    match_status,raw_json,updated_at
  ) values (
    cfg.id,v_tenant,v_contact,v_opportunity,m.id,m.message_id,m.instance_id,m.connected_phone,v_phone,
    m.chat_id,m.chat_name,m.sender_phone,m.sender_name,coalesce(m.from_me,false),m.message_type,
    coalesce(m.text_body,m.caption),m.status,m.event_at,coalesce(m.received_at,now()),
    v_match,coalesce(m.raw_json,'{}'::jsonb),now()
  )
  on conflict (instance_id,message_id) do update set
    tenant_id=excluded.tenant_id,contact_id=excluded.contact_id,opportunity_id=excluded.opportunity_id,
    source_message_row_id=excluded.source_message_row_id,connected_phone=excluded.connected_phone,
    lead_phone_normalized=excluded.lead_phone_normalized,chat_id=excluded.chat_id,chat_name=excluded.chat_name,
    sender_phone=excluded.sender_phone,sender_name=excluded.sender_name,from_me=excluded.from_me,
    message_type=excluded.message_type,body=excluded.body,status=excluded.status,event_at=excluded.event_at,
    received_at=excluded.received_at,match_status=excluded.match_status,raw_json=excluded.raw_json,updated_at=now();

  if v_opportunity is not null then
    update imobi_board.opportunities set
      last_interaction_at=greatest(coalesce(last_interaction_at,'epoch'::timestamptz),coalesce(m.event_at,m.received_at,now())),
      first_contact_at=case when first_contact_at is null and not coalesce(m.from_me,false)
        then coalesce(m.event_at,m.received_at,now()) else first_contact_at end,
      updated_at=now()
    where id=v_opportunity;
  end if;
end;
$$;
