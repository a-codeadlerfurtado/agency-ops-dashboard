  critic_version text not null,
  score numeric not null default 0,
  checks jsonb not null default '[]'::jsonb,
  reference_ids uuid[] not null default '{}'::uuid[],
  comparison jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists video_critic_runs_job_idx
  on agency_ops.video_critic_runs(job_id, created_at desc);
alter table agency_ops.video_critic_runs enable row level security;

