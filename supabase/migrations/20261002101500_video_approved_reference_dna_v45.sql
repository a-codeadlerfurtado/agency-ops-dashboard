create or replace function agency_ops.sync_v4_auto_source_job_status()
returns trigger language plpgsql security definer
set search_path to 'agency_ops','public','pg_catalog' as $$
begin
  if new.variant<>'v4_auto' then return new; end if;
  if new.status in ('CLAIMED','RENDERING') then
    update agency_ops.video_edit_jobs
       set status='RENDERING', current_stage='V4_'||coalesce(new.current_stage,new.status),
           progress_pct=greatest(progress_pct,least(99,new.progress_pct)),
           worker_id=new.worker_id, heartbeat_at=coalesce(new.heartbeat_at,now()), updated_at=now()
     where id=new.source_job_id;
  elsif new.status='UPLOADING' then
    update agency_ops.video_edit_jobs
       set status='UPLOADING',current_stage='V4_UPLOADING',
           progress_pct=greatest(progress_pct,90),worker_id=new.worker_id,updated_at=now()
     where id=new.source_job_id;
  elsif new.status='QA' then
    update agency_ops.video_edit_jobs
       set status='QA',current_stage='V4_QA',
           progress_pct=greatest(progress_pct,84),worker_id=new.worker_id,updated_at=now()
     where id=new.source_job_id;
  elsif new.status='COMPLETED' then
    if coalesce(new.renderer_version,'') like '4.5%' then
      update agency_ops.video_edit_jobs
         set status='DONE',current_stage='FINAL_READY',progress_pct=100,
             finished_at=coalesce(finished_at,now()),worker_id=new.worker_id,heartbeat_at=now(),
             renderer_version=new.renderer_version,review_mode='AUTO_APPROVED',approval_status='NOT_REQUIRED',
             last_error=null,updated_at=now()
       where id=new.source_job_id;
    else
      update agency_ops.video_edit_jobs
         set status='REVIEW_REQUIRED',current_stage='REVIEW_REQUIRED',progress_pct=100,
             finished_at=coalesce(finished_at,now()),worker_id=new.worker_id,heartbeat_at=now(),
             renderer_version=new.renderer_version,last_error=null,updated_at=now()
       where id=new.source_job_id;
    end if;
  elsif new.status='FAILED' then
    update agency_ops.video_edit_jobs
       set status='FAILED',current_stage='V4_FAILED',finished_at=coalesce(finished_at,now()),
           worker_id=new.worker_id,heartbeat_at=now(),
           last_error=coalesce(new.last_error,'v4_auto_failed'),updated_at=now()
     where id=new.source_job_id;
  elsif new.status='CANCELLED' then
    update agency_ops.video_edit_jobs
       set status='CANCELLED',current_stage='V4_CANCELLED',
           finished_at=coalesce(finished_at,now()),updated_at=now()
     where id=new.source_job_id;
  elsif new.status='RETRY' then
    update agency_ops.video_edit_jobs
       set status='RENDERING',current_stage='V4_RETRY',
           last_error=new.last_error,updated_at=now()
     where id=new.source_job_id;
  end if;
  return new;
end $$;

