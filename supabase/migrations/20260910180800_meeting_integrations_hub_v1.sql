create table if not exists agency_ops.meeting_integration_providers (
  provider_key text primary key check (provider_key ~ '^[A-Z0-9_:-]{2,80}$'),
  label text not null,
  category text not null check (category in ('GOOGLE','CRM','MESSAGING','DOCUMENTS','MEETING','MCP','IMPORT')),
  auth_mode text not null check (auth_mode in ('OAUTH2','API_KEY','INTERNAL','MCP','IMPORT')),
  capabilities jsonb not null default '[]'::jsonb,
  enabled boolean not null default true,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

