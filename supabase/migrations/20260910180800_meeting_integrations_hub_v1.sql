create table if not exists agency_ops.meeting_integration_accounts (
  id uuid primary key default gen_random_uuid(),
  owner_person text not null,
  provider_key text not null references agency_ops.meeting_integration_providers(provider_key),
  account_slot text not null default 'primary',
  external_account_id text,
  account_email text,
  display_name text,
  status text not null default 'DISCONNECTED' check (status in ('DISCONNECTED','CONNECTING','ACTIVE','ERROR','REVOKED')),
  granted_scopes text[] not null default '{}',
  enabled_capabilities jsonb not null default '[]'::jsonb,
  access_secret_id uuid,
  refresh_secret_id uuid,
  webhook_secret_id uuid,
  token_expires_at timestamptz,
  last_sync_at timestamptz,
  last_error text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(owner_person,provider_key,account_slot)
);
create index if not exists meeting_integration_accounts_owner_idx on agency_ops.meeting_integration_accounts(owner_person,status,provider_key);

create table if not exists agency_ops.meeting_oauth_states (
  id uuid primary key default gen_random_uuid(),
  owner_person text not null,
  provider_key text not null references agency_ops.meeting_integration_providers(provider_key),
  state_hash text not null unique,
  code_verifier_secret_id uuid,
  redirect_uri text not null,
  requested_scopes text[] not null default '{}',
  expires_at timestamptz not null,
  used_at timestamptz,
  created_at timestamptz not null default now()
);
create index if not exists meeting_oauth_states_expiry_idx on agency_ops.meeting_oauth_states(expires_at) where used_at is null;

create table if not exists agency_ops.meeting_integration_events (
  id bigint generated by default as identity primary key,
  owner_person text not null,
  provider_key text not null,
  account_id uuid,
  event_type text not null,
  status text not null default 'OK',
  detail jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists meeting_integration_events_owner_idx on agency_ops.meeting_integration_events(owner_person,created_at desc);

