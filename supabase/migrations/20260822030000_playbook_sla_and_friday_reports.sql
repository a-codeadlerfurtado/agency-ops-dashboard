create or replace function agency_ops.add_business_days(p_started timestamptz, p_days integer)
returns timestamptz
language plpgsql
immutable
set search_path to 'pg_catalog'
as $$
declare
  v_result timestamptz := p_started;
  v_added integer := 0;
  v_isodow integer;
begin
  if p_started is null or coalesce(p_days,0) <= 0 then return p_started; end if;
  while v_added < p_days loop
    v_result := v_result + interval '1 day';
    v_isodow := extract(isodow from (v_result at time zone 'America/Sao_Paulo'))::integer;
    if v_isodow between 1 and 5 then v_added := v_added + 1; end if;
  end loop;
  return v_result;
end;
$$;

