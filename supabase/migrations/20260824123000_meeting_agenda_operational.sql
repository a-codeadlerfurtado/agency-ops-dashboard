create or replace function public.agenda_for_current_user(
  p_from timestamptz default now()-interval '90 days',
  p_to timestamptz default now()+interval '180 days'
) returns jsonb
language plpgsql
security definer
set search_path to 'pg_catalog','public','agency_ops'
as $$
declare
  v_uid uuid := auth.uid();
  v_person text;
  v_role text;
  v_views text[];
  v_all boolean := false;
  v_from timestamptz := coalesce(p_from,now()-interval '90 days');
  v_to timestamptz := coalesce(p_to,now()+interval '180 days');
  v_events jsonb;
  v_people jsonb;
begin
  if v_uid is null then raise exception 'unauthorized' using errcode='42501'; end if;
  select nullif(trim(up.collaborator_person),'') into v_person from agency_ops.user_preferences up where up.user_key=v_uid::text limit 1;
  if v_person is null then raise exception 'profile_not_linked' using errcode='42501'; end if;
  select tr.role into v_role from agency_ops.team_roster tr where tr.person=v_person and coalesce(tr.is_former,false)=false limit 1;
  if v_role is null then raise exception 'profile_not_active' using errcode='42501'; end if;
  v_views := agency_ops.dashboard_allowed_views(v_person,v_role);
  if not ('agenda'=any(coalesce(v_views,'{}'::text[]))) then raise exception 'forbidden' using errcode='42501'; end if;
  v_all := v_person='Adler Furtado';
  if v_from > v_to then declare v_swap timestamptz := v_from; begin v_from:=v_to; v_to:=v_swap; end; end if;
  if v_to-v_from > interval '370 days' then v_to:=v_from+interval '370 days'; end if;

  select coalesce(jsonb_agg(jsonb_build_object(
    'id',q.id,'person',q.person,'client_id',q.client_id,'client_name',q.client_name,'client_lifecycle',q.client_lifecycle,
    'scheduled_for',q.scheduled_for,'duration_minutes',q.duration_minutes,'topic',q.topic,'meet_url',q.meet_url,'source',q.source,
    'confidence',q.confidence,'effective_status',q.effective_status,'actual_started_at',q.actual_started_at,'actual_ended_at',q.actual_ended_at,
    'presence_source',q.presence_source,'transcript_available',q.transcript_available,'context_available',q.context_available
  ) order by q.scheduled_for),'[]'::jsonb) into v_events
  from (
    select e.id,e.person,e.client_id,c.display_name as client_name,c.lifecycle as client_lifecycle,e.scheduled_for,e.duration_minutes,
      coalesce(nullif(e.topic,''),nullif(mp.topic,''),'Reunião / alinhamento') as topic,coalesce(e.meet_url,mp.meet_url) as meet_url,e.source,e.confidence,
      case
        when mp.id is not null and mp.ended_at is null and mp.status='IN_PROGRESS' and mp.started_at between now()-interval '3 hours' and now()+interval '30 minutes' then 'IN_PROGRESS'
        when mp.id is not null and (mp.ended_at is not null or mp.transcript_id is not null or mp.status in ('CONTEXT_AVAILABLE','COMPLETED')) then 'COMPLETED'
        when e.scheduled_for < now()-interval '3 hours' then 'NO_EVIDENCE'
        else 'SCHEDULED'
      end as effective_status,
      mp.started_at as actual_started_at,mp.ended_at as actual_ended_at,mp.source as presence_source,
      (mp.transcript_id is not null) as transcript_available,
      (mp.summary is not null or mp.transcript_id is not null or mp.status='CONTEXT_AVAILABLE') as context_available
    from agency_ops.meeting_agenda_events e
    left join agency_ops.clients c on c.id=e.client_id
    left join lateral (
      select p.* from agency_ops.meeting_presence_events p
      where p.person=e.person and p.status<>'CANCELLED'
        and p.started_at between e.scheduled_for-interval '4 hours' and e.scheduled_for+interval '4 hours'
      order by case when e.client_id is not null and p.client_id=e.client_id then 0 when e.client_id is null or p.client_id is null then 1 else 2 end,
        abs(extract(epoch from (p.started_at-e.scheduled_for))) limit 1
    ) mp on true
    where e.status='SCHEDULED' and e.scheduled_for between v_from and v_to and (v_all or e.person=v_person)
    order by e.scheduled_for limit 1200
  ) q;

  select coalesce(jsonb_agg(jsonb_build_object('person',x.person,'role',x.role) order by x.person),'[]'::jsonb) into v_people
  from (select tr.person,tr.role from agency_ops.team_roster tr where coalesce(tr.is_former,false)=false and (v_all or tr.person=v_person)) x;

  return jsonb_build_object('ok',true,'profile',jsonb_build_object('person',v_person,'role',v_role,'can_view_all',v_all),
    'scope',case when v_all then 'ALL_TEAM' else 'SELF_ONLY' end,'events',v_events,'people',v_people,
    'range',jsonb_build_object('from',v_from,'to',v_to),'generated_at',now());
end
$$;

